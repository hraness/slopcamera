import { expect, test } from "bun:test"
import { mkdtemp, readFile, rm, mkdir } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import sharp from "sharp"
import { createProcessLocalHostResourceCoordinator } from "./host-resources.js"
import { repairSlopcameraPixelLandscape } from "./pixel-landscape-repair.js"
import { parseSlopcameraPixelLandscapeManifest, type SlopcameraLandscapeRunDependencies } from "./pixel-landscape-run.js"

const manifest = () => parseSlopcameraPixelLandscapeManifest({
  kind: "slopcamera.pixel-landscape", schemaVersion: 1, product: "Example", brief: "An orbital studio", rubric: "Demand continuous tracks.",
  theme: { background: "#eff1f5", primary: "#1750bf", secondary: "#dce0e8" },
  sections: [{ id: "sky", description: "Sky observatory" }, { id: "garden", description: "Underground garden" }],
  candidates: [{ id: "first", direction: "Folded planes" }],
  generation: { provider: "vertex", model: "gemini-3-pro-image", judgeModel: "gemini-3.1-pro-preview", resolution: "2K", rounds: 1, concurrency: 1, maxImageCalls: 2, maxJudgeCalls: 1 },
  processing: { width: 64, panelHeight: 114, overlap: 16, pixelSize: 4, alphaMax: 1, gamma: 1.2, quietCenter: 0.45, upscale: 1 },
})

async function fixture() {
  const root = await mkdtemp(join(tmpdir(), "slopcamera-repair-"))
  const source = await sharp({ create: { width: 64, height: 212, channels: 4, background: { r: 200, g: 200, b: 200, alpha: 0.5 } } }).png().toBuffer()
  const patch = await sharp({ create: { width: 64, height: 48, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0.5 } } }).png().toBuffer()
  let images = 0
  let judges = 0
  const dependencies: SlopcameraLandscapeRunDependencies = {
    hostResourceCoordinator: createProcessLocalHostResourceCoordinator(),
    generate: async input => {
      images++
      expect(input.references).toHaveLength(1)
      expect(input.aspectRatio).toBe("4:3")
      expect(await readFile(join(root, "out", "bridge-1.request.json"), "utf8")).toContain("prepared")
      return { bytes: patch, provider: input.provider, model: input.model, mediaType: "image/png", requestId: "fake-image", warnings: [] }
    },
    judge: async input => {
      judges++
      expect(input.images).toHaveLength(3)
      expect(await readFile(join(root, "out", "judge.request.json"), "utf8")).toContain("prepared")
      return { text: JSON.stringify({ relevance: 9, continuity: 9, composition: 9, detail: 9, defects: [], revision: "" }), provider: input.provider, model: input.model, requestId: "fake-judge" }
    },
  }
  return { root, source, patch, dependencies, counts: () => ({ images, judges }), input: { source, manifest: manifest(), outputDirectory: join(root, "out"), allowCloudUpload: true as const, maxImageCalls: 2, maxJudgeCalls: 1 } }
}

test("repair changes only the central band, feathers alpha correctly and retains exact generated bytes", async () => {
  const f = await fixture()
  try {
    const result = await repairSlopcameraPixelLandscape(f.input, f.dependencies)
    expect(result.status).toBe("accepted-by-model")
    expect(f.counts()).toEqual({ images: 1, judges: 1 })
    const original = await sharp(f.source).ensureAlpha().raw().toBuffer()
    const repaired = await sharp(await readFile(result.artifacts.raster.path)).ensureAlpha().raw().toBuffer()
    // Crop y82..130; ONLY inner y90..122 can change. Outer band endpoints remain exact.
    for (let y = 0; y < 212; y++) {
      const row = repaired.subarray(y * 64 * 4, (y + 1) * 64 * 4)
      if (y <= 90 || y >= 121) expect(row).toEqual(original.subarray(y * 64 * 4, (y + 1) * 64 * 4))
      for (let x = 0; x < 64; x++) expect(repaired[(y * 64 + x) * 4 + 3]).toBe(128)
    }
    expect(repaired[(105 * 64) * 4]).toBe(0)
    expect(repaired[(91 * 64) * 4]).toBeGreaterThan(0)
    expect(repaired[(91 * 64) * 4]).toBeLessThan(200)
    expect(await readFile(join(f.root, "out", "original.png"))).toEqual(f.source)
    expect(await readFile(join(f.root, "out", "bridge-1.generated.png"))).toEqual(f.patch)
    expect(JSON.parse(await readFile(join(f.root, "out", "bridge-1.result.json"), "utf8")).sha256).toMatch(/^[a-f0-9]{64}$/u)
    expect(await readFile(join(f.root, "out", "receipt.json"), "utf8")).toContain("accepted-by-model")
  } finally { await rm(f.root, { recursive: true, force: true }) }
})

test("caps, upload permission, wrong source dimensions and existing output fail before requests", async () => {
  const f = await fixture()
  try {
    await expect(repairSlopcameraPixelLandscape({ ...f.input, maxImageCalls: 0 }, f.dependencies)).rejects.toThrow("call")
    const three = { ...manifest(), sections: [...manifest().sections, { id: "roots", description: "Roots" }] }
    await expect(repairSlopcameraPixelLandscape({ ...f.input, manifest: three, maxImageCalls: 1 }, f.dependencies)).rejects.toThrow("cap")
    await expect(repairSlopcameraPixelLandscape({ ...f.input, maxJudgeCalls: 2 }, f.dependencies)).rejects.toThrow("call")
    await expect(repairSlopcameraPixelLandscape({ ...f.input, allowCloudUpload: false as true }, f.dependencies)).rejects.toThrow("allow-cloud-upload")
    await expect(repairSlopcameraPixelLandscape({ ...f.input, manifest: three }, f.dependencies)).rejects.toThrow("sized")
    await mkdir(f.input.outputDirectory)
    await expect(repairSlopcameraPixelLandscape(f.input, f.dependencies)).rejects.toThrow()
    expect(f.counts()).toEqual({ images: 0, judges: 0 })
  } finally { await rm(f.root, { recursive: true, force: true }) }
})

test("feathering uses premultiplied alpha when a bridge is more opaque than source", async () => {
  const f = await fixture()
  try {
    const opaque = await sharp({ create: { width: 64, height: 48, channels: 4, background: "black" } }).png().toBuffer()
    const result = await repairSlopcameraPixelLandscape(f.input, { ...f.dependencies, generate: async input => ({ bytes: opaque, provider: input.provider, model: input.model, mediaType: "image/png", requestId: "opaque", warnings: [] }) })
    const repaired = await sharp(await readFile(result.artifacts.raster.path)).ensureAlpha().raw().toBuffer()
    // y94 is halfway through the eight-row feather: alpha=.5*.5 + 1*.5,
    // while unpremultiplied gray is approximately 200*.25/.75 = 67, not 100.
    expect(repaired[(94 * 64) * 4]).toBe(67)
    expect(repaired[(94 * 64) * 4 + 3]).toBe(192)
    expect(repaired[(105 * 64) * 4 + 3]).toBe(255)
    expect(repaired[(80 * 64) * 4 + 3]).toBe(128)
  } finally { await rm(f.root, { recursive: true, force: true }) }
})

test("failed generation stops once, retains the prepared attempt and never judges or retries", async () => {
  const f = await fixture()
  let calls = 0
  try {
    await expect(repairSlopcameraPixelLandscape(f.input, { ...f.dependencies, generate: async () => { calls++; throw new Error("private provider payload") } })).rejects.toThrow("may have been charged")
    expect(calls).toBe(1)
    expect(f.counts().judges).toBe(0)
    const failure = await readFile(join(f.root, "out", "bridge-1.failure.json"), "utf8")
    expect(failure).toContain("failed-or-ambiguous")
    expect(failure).not.toContain("private provider payload")
    expect(JSON.parse(await readFile(join(f.root, "out", "receipt.json"), "utf8")).imageCalls).toBe(1)
  } finally { await rm(f.root, { recursive: true, force: true }) }
})

test("failed judgement preserves final images and returns needs-review without retry", async () => {
  const f = await fixture()
  let calls = 0
  try {
    const result = await repairSlopcameraPixelLandscape(f.input, { ...f.dependencies, judge: async () => { calls++; throw new Error("private judging data") } })
    expect(calls).toBe(1)
    expect(result.status).toBe("needs-review")
    expect(result.judgement).toBeNull()
    expect((await readFile(result.artifacts.mask.path)).byteLength).toBeGreaterThan(0)
    expect(await readFile(join(f.root, "out", "judge.failure.json"), "utf8")).toContain("automaticRetry")
  } finally { await rm(f.root, { recursive: true, force: true }) }
})

test("a high model mean with blocking defects cannot accept a repair", async () => {
  const f = await fixture()
  try {
    const result = await repairSlopcameraPixelLandscape(f.input, { ...f.dependencies, judge: async input => ({ text: JSON.stringify({ relevance: 10, continuity: 10, composition: 10, detail: 10, defects: ["left rail restarts"], revision: "connect rail" }), provider: input.provider, model: input.model, requestId: "fake" }) })
    expect(result.status).toBe("needs-review")
    expect(result.judgement?.overall).toBe(10)
  } finally { await rm(f.root, { recursive: true, force: true }) }
})
